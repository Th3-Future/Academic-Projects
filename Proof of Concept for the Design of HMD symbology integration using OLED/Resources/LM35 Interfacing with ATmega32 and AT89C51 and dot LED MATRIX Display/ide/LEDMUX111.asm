ORG 0H
	MOV TMOD,#01H
	MOV R2,#0FEH;11111110
BACK:	MOV DPTR,#MY
	MOV R3,#050H
LOOP1:	MOV R4,#08H
LOOP:	MOV A,R2
	MOV P3,A
	RL A
	MOV R2,A
	MOV A,R4
	MOVC A,@A+DPTR
	MOV P2,A
	ACALL DELAY
	DJNZ R4,LOOP
	DJNZ R3,LOOP1
	SJMP BACK
DELAY:	MOV TH0,#0FFH
	MOV TL0,#0
	SETB TR0
HERE:	JNB TF0,HERE
	CLR TR0
	CLR TF0
	RET
ORG 50H
MY:	DB 00000000B,00000000B,00111100B,00100000B,00111100B,00000100B,00111100B,00000000B
END
